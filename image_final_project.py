import torch

def train_model(model, train_loader, optimizer, criterion, device):
    """
    Trains the CNN model for one epoch.

    Args:
        model: The CNN model to train.
        train_loader: The data loader for the training dataset.
        optimizer: The optimizer for updating model weights.
        criterion: The loss function (Cross-Entropy Loss).
        device: The device to train on ('cuda' or 'cpu').

    Returns:
        The average loss for the epoch.
    """
    model.train()
    running_loss = 0.0
    for images, labels in train_loader:

        images = images.to(device)
        labels = labels.to(device)


        optimizer.zero_grad()

        outputs = model(images)
        loss = criterion(outputs, labels)

        loss.backward()
        optimizer.step()

        running_loss += loss.item()


    epoch_loss = running_loss / len(train_loader)
    return epoch_loss

import torch

def test_model(model, test_loader, device):
    """
    Tests the CNN model and calculates its accuracy.

    Args:
        model: The trained CNN model.
        test_loader: The data loader for the testing dataset.
        device: The device to test on ('cuda' or 'cpu').

    Returns:
        The accuracy of the model on the test dataset.
    """
    model.eval()
    correct = 0
    total = 0
    with torch.no_grad():
        for images, labels in test_loader:

            images = images.to(device)
            labels = labels.to(device)


            outputs = model(images)


            _, predicted = torch.max(outputs.data, 1)


            total += labels.size(0)
            correct += (predicted == labels).sum().item()

    accuracy = 100 * correct / total
    return accuracy

