def predict_image(model, image_input, transform, device):

    model.eval()

    if isinstance(image_input, str):
        try:

            image = Image.open(image_input)


            if image.mode != 'L':
                image = image.convert('L')


            image = transform(image)


            image = image.unsqueeze(0)
        except FileNotFoundError:
            print(f"Error: Image file not found at {image_input}")
            return None, None
        except Exception as e:
            print(f"An error occurred while loading or processing the image: {e}")
            return None, None

    elif isinstance(image_input, torch.Tensor):

        image = image_input

    else:
        print("Error: image_input must be a file path (str) or a PyTorch Tensor.")
        return None, None

    image = image.to(device)

    with torch.no_grad():
        outputs = model(image)


    probabilities = torch.softmax(outputs, dim=1)

    predicted_class_index = torch.argmax(probabilities, dim=1)


    return predicted_class_index.item(), probabilities[0]

